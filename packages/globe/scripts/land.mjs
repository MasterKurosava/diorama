// Bakes the land mask of `globe` into src/land.ts. Not part of the build: run it by hand when the
// source or the format changes, and commit the result.
//   node packages/globe/scripts/land.mjs [ne_110m_land.geojson]
// Without a path it downloads Natural Earth 1:110m land (public domain) at a pinned commit.
//
// A cell of 0.5° (720 x 360, rows from the north, columns from 180° W) is land when its centre is
// inside a polygon by the even-odd rule. The cells, row after row, become alternating runs of sea
// and land, sea first. A run is written as digits over printable characters without the quote
// and the backslash: the last digit is one of the first TERMINAL characters, the ones before it
// (if the run is TERMINAL or longer) come from the rest, most significant first.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const COMMIT = '693f11422f4e08d2da4566b854dda53eb7c39fb3'
const DATE = '2020-12-13'
const SOURCE = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${COMMIT}/geojson/ne_110m_land.geojson`
const WIDTH = 720
const HEIGHT = 360
const CELL = 180 / HEIGHT
// Must match the decoder in src/globe.ts.
const DIGITS = Array.from({ length: 92 }, (_, i) => String.fromCharCode(35 + i))
  .filter((c) => c !== "'" && c !== '\\')
  .join('')
const TERMINAL = 80
const BASE = DIGITS.length - TERMINAL

/** Land cells of every polygon, by scanlines through the cell centres. */
function rasterize(geojson) {
  const cells = new Uint8Array(WIDTH * HEIGHT)
  const polygons = geojson.features.flatMap(({ geometry: g }) =>
    g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [],
  )
  for (const rings of polygons) {
    for (let row = 0; row < HEIGHT; row++) {
      const lat = 90 - (row + 0.5) * CELL
      const xs = []
      for (const ring of rings) {
        for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
          const [x1, y1] = ring[i]
          const [x2, y2] = ring[j]
          if (y1 > lat !== y2 > lat) xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1))
        }
      }
      xs.sort((a, b) => a - b)
      // Even-odd: the centres between a pair of crossings are inside.
      for (let k = 0; k + 1 < xs.length; k += 2) {
        const from = Math.max(0, Math.ceil((xs[k] + 180) / CELL - 0.5))
        const to = Math.min(WIDTH - 1, Math.floor((xs[k + 1] + 180) / CELL - 0.5))
        cells.fill(1, row * WIDTH + from, row * WIDTH + to + 1)
      }
    }
  }
  return cells
}

/** Runs of sea and land, sea first, as printable digits. */
function encode(cells) {
  let out = ''
  let at = 0
  let land = 0
  while (at < cells.length) {
    let end = at
    while (end < cells.length && cells[end] === land) end++
    const run = end - at
    let lead = ''
    for (let q = Math.floor(run / TERMINAL); q > 0; q = Math.floor(q / BASE))
      lead = DIGITS[TERMINAL + (q % BASE)] + lead
    out += lead + DIGITS[run % TERMINAL]
    at = end
    land ^= 1
  }
  return out
}

const path = process.argv[2]
const text = path ? readFileSync(path, 'utf8') : await (await fetch(SOURCE)).text()
const cells = rasterize(JSON.parse(text))
const mask = encode(cells)
const sha = createHash('sha256').update(mask).digest('hex')
const land = cells.reduce((sum, c) => sum + c, 0)
const file = join(dirname(fileURLToPath(import.meta.url)), '../src/land.ts')
writeFileSync(
  file,
  [
    '// Generated by scripts/land.mjs, do not edit: run the script again.',
    `// Natural Earth 1:110m land (ne_110m_land, public domain), commit ${COMMIT.slice(0, 7)} of ${DATE}.`,
    `// ${WIDTH} x ${HEIGHT} cells of ${CELL}°, rows from the north, run-length encoded. sha256 ${sha}`,
    '',
    '/** The land mask of `globe`. */',
    `const land: string =\n  '${mask}'`,
    'export default land',
    '',
  ].join('\n'),
)
console.log(`${mask.length} characters, ${land} land cells of ${cells.length}: ${file}`)
