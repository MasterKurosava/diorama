// diorama/vite finds the site's effects folder, serves it as the `@dioramajs/diorama/generated` registry
// (one lazy import per file), writes the registry's types next to it and wires HMR per file.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, extname, join, resolve } from 'node:path'
import { convert, entryMeta } from '@dioramajs/glsl/convert'
import type { Plugin, ResolvedConfig, ViteDevServer } from 'vite'
import { entry, type Meta, paramsType, readMeta } from './meta'
import { bare, posix, specifier } from './paths'

/** Options of the build plugins. */
export interface DioramaPluginOptions {
  /** The effects folder, relative to the Vite root. Default 'src/effects'. */
  readonly dir?: string
  /** The types file, relative to the root, or `false` for none. Default 'src/diorama.gen.d.ts'. */
  readonly types?: string | false
}

const SLOT = '@dioramajs/diorama/generated'
const VIRTUAL = '\0diorama:generated'
/** Extensions of effect modules in the folder. */
export const CODE: ReadonlySet<string> = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs', '.mts'])
/** Extension of a fragment shader effect. */
export const SHADER = '.frag'
const NAME = /^[a-z][a-z0-9-]*$/

/** A single-quoted string literal, in the generated files' style. */
export const quote = (text: string): string =>
  `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
/** An object key, bare when possible. */
export const key = (name: string): string =>
  /^[a-z_$][a-z0-9_$]*$/i.test(name) ? name : quote(name)
/** `HeroGlow` and `hero_glow` both become `hero-glow`. */
export const effectName = (file: string): string =>
  basename(file, extname(file))
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[_\s]+/g, '-')
    .toLowerCase()

/** An effect file found in the folder. */
export interface Found {
  /** The effect name, from the file name. */
  readonly name: string
  /** Absolute, with forward slashes. */
  readonly file: string
  /** A GLSL file rather than a module. */
  readonly shader: boolean
  /** What the light part knows before the module loads. */
  readonly meta?: Meta | undefined
}

/** A shader's params from its bindings and its .vert's, the rest from its `@diorama` pragmas. */
function shaderMeta(file: string): Meta | undefined {
  const read = (path: string) =>
    existsSync(path) ? convert(readFileSync(path, 'utf8'), { filename: path }).shader : undefined
  try {
    const fragment = read(file)
    if (!fragment) return undefined
    const { params, ...rest } = entryMeta(fragment, read(file.replace(/\.frag$/, '.vert')))
    const meta: Meta = { ...(Object.keys(params).length ? { params } : {}), ...rest }
    return Object.keys(meta).length ? meta : undefined
  } catch {
    // The bundler's GLSL plugin or loader reports the error when the module loads.
    return undefined
  }
}

/**
 * The folder's effects, one per code file (not `*.d.ts`, not `_private`) and per fragment shader
 * without a code file of the same name. Sorted by name. Bad or repeated names are skipped.
 */
export function scan(dir: string, shaders: boolean): { found: Found[]; skipped: string[] } {
  const found = new Map<string, Found>()
  const skipped: string[] = []
  if (!existsSync(dir)) return { found: [], skipped }
  const files = readdirSync(dir).sort()
  for (const shader of [false, true]) {
    for (const entry of files) {
      const ext = extname(entry)
      if (entry.startsWith('_') || entry.startsWith('.') || entry.endsWith('.d.ts')) continue
      if (shader ? !shaders || ext !== SHADER : !CODE.has(ext)) continue
      const name = effectName(entry)
      if (!NAME.test(name)) {
        skipped.push(`${entry}: "${name}" is not a kebab-case effect name`)
        continue
      }
      // A code file beats a shader of the same name, since it is the shader's glue.
      if (found.has(name)) {
        if (!shader) skipped.push(`${entry}: "${name}" is taken by another file`)
        continue
      }
      const file = posix(join(dir, entry))
      const meta = shader ? shaderMeta(file) : readMeta(readFileSync(file, 'utf8'))
      found.set(name, { name, file, shader, meta })
    }
  }
  return { found: [...found.values()].sort((a, b) => a.name.localeCompare(b.name)), skipped }
}

/**
 * Lines of a braced block. An empty one is `{}` on the opening line, as Biome and Prettier print
 * it, so formatting a generated file for an empty folder leaves it as written.
 */
export const braces = (open: string, rows: readonly string[], close: string): string[] =>
  rows.length ? [open, ...rows, close] : [`${open}${close.trimStart()}`]

/** Lazy imports with what is known before load. Shaders through @dioramajs/glsl's `?effect`. */
export function registry(found: readonly Found[]): string {
  const rows = found.map((f) => {
    const load = `() => import(${quote(f.shader ? `${f.file}?effect` : f.file)})`
    return `  ${key(f.name)}: ${entry(load, f.meta)},`
  })
  return [
    '// Generated by @dioramajs/diorama/vite from the effects folder.',
    ...braces('export const effects = {', rows, '}'),
    '',
  ].join('\n')
}

/** A shader's effect type, from the params of its bindings. */
export const shaderType = (f: Found): string =>
  `import('@dioramajs/diorama').Effect<${paramsType(f.meta?.params)}>`

/** Types that check effect names in `attach('.x', 'name')` and `data-dio`. */
export function declarations(found: readonly Found[], from: string): string {
  const rows = found.map((f) => {
    const type = f.shader
      ? shaderType(f)
      : `typeof import(${quote(bare(specifier(from, f.file)))}).default`
    return `    ${key(f.name)}: ${type}`
  })
  return [
    '// Generated by @dioramajs/diorama/vite from the effects folder. Do not edit; commit it.',
    "declare module '@dioramajs/diorama' {",
    ...braces('  interface SiteEffects {', rows, '  }'),
    '}',
    '',
    'export {}',
    '',
  ].join('\n')
}

/** Self-acceptance for an effect file. A new definition replaces the old one by key. */
const hmr = (name: string): string =>
  `\n;import { redefine as __dioramaRedefine } from '@dioramajs/diorama'\n` +
  `if (import.meta.hot) import.meta.hot.accept((m) => { if (m && m.default) __dioramaRedefine(${JSON.stringify(name)}, m.default) })\n`

/** Vite plugin, `plugins: [diorama()]`. */
export function diorama(options: DioramaPluginOptions = {}): Plugin {
  let root = process.cwd()
  let dir = ''
  let types: string | undefined
  let serve = false
  let shaders = false
  let found: Found[] = []
  let server: ViteDevServer | undefined

  const refresh = (warn: (message: string) => void): void => {
    const result = scan(dir, shaders)
    found = result.found
    for (const message of result.skipped) warn(`[diorama] skipped ${message}`)
    if (!types) return
    const text = declarations(found, resolve(types, '..'))
    // Write only on change. A rewrite would wake the type checker and file watchers.
    if (!existsSync(types) || readFileSync(types, 'utf8') !== text) writeFileSync(types, text)
  }

  return {
    name: 'diorama',
    enforce: 'pre',
    config: () => ({
      // A pre-bundled copy would bake the empty slot in.
      optimizeDeps: { exclude: ['@dioramajs/diorama'] },
    }),
    configResolved(config: ResolvedConfig) {
      root = config.root
      serve = config.command === 'serve'
      dir = posix(resolve(root, options.dir ?? 'src/effects'))
      types =
        options.types === false ? undefined : resolve(root, options.types ?? 'src/diorama.gen.d.ts')
      shaders = config.plugins.some((p) => p.name === 'diorama-glsl')
      refresh((message) => config.logger.warn(message))
    },
    resolveId(source) {
      return source === SLOT ? VIRTUAL : null
    },
    load(id) {
      if (id !== VIRTUAL) return null
      return registry(found)
    },
    transform(code, id) {
      // A query (?raw, ?url, ?worker) makes another module from the file, which needs no HMR glue.
      if (!serve || id.includes('?')) return null
      const file = posix(id)
      const effect = found.find((f) => !f.shader && f.file === file)
      return effect ? { code: code + hmr(effect.name), map: null } : null
    },
    configureServer(dev) {
      server = dev
      const changed = (path: string): void => {
        if (posix(resolve(path, '..')) !== dir) return
        const before = registry(found)
        refresh((message) => dev.config.logger.warn(message))
        // An edit that keeps the metadata (an effect's body) stays a hot update of its module.
        if (registry(found) === before) return
        const module = server?.moduleGraph.getModuleById(VIRTUAL)
        if (module) server?.moduleGraph.invalidateModule(module)
        server?.ws.send({ type: 'full-reload' })
      }
      dev.watcher.add(dir)
      dev.watcher.on('add', changed)
      dev.watcher.on('unlink', changed)
      dev.watcher.on('change', changed)
    },
  }
}

export default diorama
