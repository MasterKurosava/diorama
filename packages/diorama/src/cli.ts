// diorama gen writes the effects folder's registry or types without a bundler (CI typecheck,
// esbuild, Parcel or Bun sites, pages without a build). The format follows the --out extension.
import {
  existsSync,
  type FSWatcher,
  mkdirSync,
  readFileSync,
  realpathSync,
  watch,
  writeFileSync,
} from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { parseArgs } from 'node:util'
import { nextModule } from './next'
import { effectsDir, posix, specifier } from './paths'
import { declarations, type Found, key, quote, scan } from './vite'

export interface CliIO {
  readonly out: (text: string) => void
  readonly err: (text: string) => void
}
export interface CliRun {
  /** Exit code of the first pass. */
  readonly code: number
  close(): void
}

const USAGE = `diorama gen [--dir src/effects] [--out src/diorama.gen.d.ts | src/diorama.gen.ts | fx/registry.js]
            [--check] [--watch]`

const JS = /\.m?js$/

/** The registry for a page without a build. No types, relative URLs with their extension. */
export function jsModule(found: readonly Found[], from: string): string {
  const rows = found.map(
    (f) => `  ${key(f.name)}: () => import(${quote(specifier(from, f.file))}),`,
  )
  return [
    '// Generated by diorama gen from the effects folder. Do not edit.',
    'export const effects = {',
    ...rows,
    '}',
    '',
  ].join('\n')
}

/** The file's text in the format its extension asks for, plus what was left out. */
export function generate(dir: string, out: string): { text: string; skipped: string[] } {
  const { found, skipped } = scan(posix(dir), false)
  const from = dirname(out)
  if (out.endsWith('.d.ts')) return { text: declarations(found, from), skipped }
  if (JS.test(out)) {
    const pages = found.filter((f) => JS.test(f.file))
    for (const f of found) {
      if (!pages.includes(f))
        skipped.push(`${relative(dir, f.file)}: a page without a build imports .js`)
    }
    return { text: jsModule(pages, from), skipped }
  }
  return { text: nextModule(found, from, 'diorama gen'), skipped }
}

/** Runs the CLI in-process. `bin/diorama.mjs` exits with `code`. */
export function run(
  argv: readonly string[],
  io: CliIO = {
    out: (t) => process.stdout.write(`${t}\n`),
    err: (t) => process.stderr.write(`${t}\n`),
  },
  cwd: string = process.cwd(),
): CliRun {
  let parsed: ReturnType<typeof parse>
  function parse() {
    return parseArgs({
      args: [...argv],
      allowPositionals: true,
      options: {
        dir: { type: 'string' },
        out: { type: 'string' },
        check: { type: 'boolean' },
        watch: { type: 'boolean' },
        help: { type: 'boolean', short: 'h' },
      },
    })
  }
  try {
    parsed = parse()
  } catch (error) {
    io.err(`${(error as Error).message}\n${USAGE}`)
    return { code: 2, close() {} }
  }
  const { values, positionals } = parsed
  if (values.help) {
    io.out(USAGE)
    return { code: 0, close() {} }
  }
  if (positionals[0] !== 'gen' || positionals.length > 1) {
    io.err(USAGE)
    return { code: 2, close() {} }
  }
  const dir = resolve(cwd, values.dir ?? effectsDir(cwd))
  const out = resolve(cwd, values.out ?? resolve(dir, '../diorama.gen.d.ts'))
  const shown = posix(relative(cwd, out))

  const pass = (): number => {
    const { text, skipped } = generate(dir, out)
    for (const message of skipped) io.err(`skipped ${message}`)
    const fresh = existsSync(out) && readFileSync(out, 'utf8') === text
    if (values.check) {
      if (!fresh) io.err(`${shown} is stale: run diorama gen`)
      return fresh ? 0 : 1
    }
    // Write only on change. A rewrite would wake type checkers and file watchers.
    if (!fresh) {
      mkdirSync(dirname(out), { recursive: true })
      writeFileSync(out, text)
    }
    io.out(fresh ? `${shown} is up to date` : `wrote ${shown}`)
    return 0
  }
  const code = pass()
  if (!values.watch || values.check) return { code, close() {} }

  let watcher: FSWatcher | undefined
  try {
    // Use the long path. On Windows libuv can abort the process watching an 8.3 short one.
    watcher = watch(realpathSync.native(dir), () => pass())
    // Windows reports EPERM when the watched folder goes away. Stop quietly.
    watcher.on('error', () => watcher?.close())
  } catch {
    io.err(`cannot watch ${posix(relative(cwd, dir))}`)
    return { code: 1, close() {} }
  }
  io.out(`watching ${posix(relative(cwd, dir))}`)
  return { code, close: () => watcher?.close() }
}
