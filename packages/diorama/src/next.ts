// diorama/next, used as `export default withDiorama(nextConfig)` in next.config. Neither webpack
// nor Turbopack has virtual modules, so the registry and its types go to a real file
// (src/diorama.gen.ts) and `diorama/generated` is aliased to it in both bundlers.
import { existsSync, readFileSync, realpathSync, watch, writeFileSync } from 'node:fs'
import { relative, resolve } from 'node:path'
import { bare, effectsDir, posix, specifier } from './paths'
import { type Found, key, quote, scan } from './vite'

export interface WithDioramaOptions {
  /** The effects folder from the project root. Default 'src/effects', or 'effects' without src. */
  readonly dir?: string
  /** The generated module. Default `diorama.gen.ts` next to the folder. */
  readonly out?: string
}

type Webpack = (config: WebpackConfig, context: unknown) => WebpackConfig
interface WebpackConfig {
  resolve?: { alias?: Record<string, unknown> }
}
export interface NextConfigLike {
  readonly webpack?: Webpack | null
  readonly turbopack?: { readonly resolveAlias?: Readonly<Record<string, unknown>> }
}

/** One watcher per effects folder. Next evaluates its config more than once per process. */
const writers = new Map<string, () => void>()

/** Lazy imports and the registry's types in one file. */
export function nextModule(found: readonly Found[], from: string, tool = 'diorama/next'): string {
  const spec = (f: Found): string => bare(specifier(from, f.file))
  const code = found.filter((f) => !f.shader)
  return [
    `// Generated by ${tool} from the effects folder. Do not edit; commit it.`,
    "import type { EffectEntries } from 'diorama'",
    '',
    'export const effects: EffectEntries = {',
    ...code.map((f) => `  ${key(f.name)}: () => import(${quote(spec(f))}),`),
    '}',
    '',
    "declare module 'diorama' {",
    '  interface SiteEffects {',
    ...code.map((f) => `    ${key(f.name)}: typeof import(${quote(spec(f))}).default`),
    '  }',
    '}',
    '',
  ].join('\n')
}

/** Wraps a Next config so the effects folder becomes `diorama/generated`. */
export function withDiorama<T extends NextConfigLike>(
  config: T,
  options: WithDioramaOptions = {},
): T {
  const root = process.cwd()
  const dir = resolve(root, options.dir ?? effectsDir(root))
  const out = resolve(root, options.out ?? resolve(dir, '../diorama.gen.ts'))
  const write = (): void => {
    const text = nextModule(scan(posix(dir), false).found, resolve(out, '..'))
    if (!existsSync(out) || readFileSync(out, 'utf8') !== text) writeFileSync(out, text)
  }
  write()
  // Dev servers pick up added and removed files. A build reads the folder once.
  if (process.env.NODE_ENV !== 'production' && existsSync(dir)) {
    // Use the long path. On Windows libuv aborts the process watching an 8.3 short one.
    const real = realpathSync.native(dir)
    if (!writers.has(real)) watch(real, () => writers.get(real)?.()).unref()
    writers.set(real, write)
  }
  const webpack = config.webpack
  return {
    ...config,
    webpack: (cfg: WebpackConfig, context: unknown) => {
      const next = webpack ? webpack(cfg, context) : cfg
      next.resolve ??= {}
      next.resolve.alias = { ...next.resolve.alias, 'diorama/generated$': out }
      return next
    },
    turbopack: {
      ...config.turbopack,
      resolveAlias: {
        ...config.turbopack?.resolveAlias,
        'diorama/generated': `./${posix(relative(root, out))}`,
      },
    },
  }
}

export default withDiorama
