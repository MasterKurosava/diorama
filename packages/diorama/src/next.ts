// diorama/next, used as `export default withDiorama(nextConfig)` in next.config. Neither webpack
// nor Turbopack has virtual modules, so the registry and its types go to a real file
// (src/diorama.gen.ts) and `dioramajs/generated` is aliased to it in both bundlers.
import { existsSync, readFileSync, realpathSync, watch, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, relative, resolve } from 'node:path'
import { entry, fields } from './meta'
import { bare, effectsDir, posix, specifier } from './paths'
import { braces, type Found, key, quote, scan, shaderType } from './vite'

/** Options of `withDiorama`. */
export interface WithDioramaOptions {
  /** The effects folder from the project root. Default 'src/effects', or 'effects' without src. */
  readonly dir?: string
  /** The generated module. Default `diorama.gen.ts` next to the folder. */
  readonly out?: string
}

// A method, so its parameters are bivariant: Next types `context` as its own WebpackConfigContext.
interface WebpackHook {
  hook(config: WebpackConfig, context: unknown): WebpackConfig
}
type Webpack = WebpackHook['hook']
interface WebpackConfig {
  resolve?: { alias?: Record<string, unknown> }
  module?: { rules?: unknown[] }
}
/** The part of a Next config `withDiorama` reads and writes. */
export interface NextConfigLike {
  /** The site's webpack hook. It runs first, then ours adds the alias and the GLSL rule. */
  readonly webpack?: Webpack | null
  /** Turbopack aliases and loader rules, merged with ours. */
  readonly turbopack?: {
    readonly resolveAlias?: Readonly<Record<string, unknown>>
    readonly rules?: Readonly<Record<string, unknown>>
  }
}

/** One watcher per effects folder. Next evaluates its config more than once per process. */
const writers = new Map<string, () => void>()

/** Lazy imports with their metadata and the registry's types in one file. */
export function nextModule(found: readonly Found[], from: string, tool = 'dioramajs/next'): string {
  const spec = (f: Found): string => bare(specifier(from, f.file))
  const row = (f: Found): string => {
    if (!f.shader) return `  ${key(f.name)}: ${entry(`() => import(${quote(spec(f))})`, f.meta)},`
    // A GLSL module has no types of its own. Its effect type is written below from its bindings.
    return [
      `  ${key(f.name)}: {`,
      '    // @ts-ignore',
      `    load: () => import(${quote(specifier(from, f.file))}),`,
      ...fields(f.meta).map((field) => `    ${field},`),
      '  },',
    ].join('\n')
  }
  const type = (f: Found): string =>
    f.shader ? shaderType(f) : `typeof import(${quote(spec(f))}).default`
  return [
    `// Generated by ${tool} from the effects folder. Do not edit; commit it.`,
    "import type { EffectEntries } from 'dioramajs'",
    '',
    ...braces('export const effects: EffectEntries = {', found.map(row), '}'),
    '',
    "declare module 'dioramajs' {",
    ...braces(
      '  interface SiteEffects {',
      found.map((f) => `    ${key(f.name)}: ${type(f)}`),
      '  }',
    ),
    '}',
    '',
  ].join('\n')
}

const require = createRequire(import.meta.url)
/** @dioramajs/glsl as diorama installed it: a site with only `dioramajs` cannot resolve it itself. */
const glsl = (): { loader: string; runtime: string } => ({
  loader: require.resolve('@dioramajs/glsl/loader'),
  runtime: dirname(require.resolve('@dioramajs/glsl/package.json')),
})

/** Wraps a Next config so the effects folder becomes `dioramajs/generated`. */
export function withDiorama<T extends object = NextConfigLike>(
  // An intersection, not a constraint: as a constraint, a type of only optional fields rejects
  // configs that set none of them (TypeScript's weak type check). The default is for a config
  // typed as NextConfigLike itself, which leaves nothing to infer T from.
  config: T & NextConfigLike,
  options: WithDioramaOptions = {},
): T {
  const root = process.cwd()
  const dir = resolve(root, options.dir ?? effectsDir(root))
  const out = resolve(root, options.out ?? resolve(dir, '../diorama.gen.ts'))
  const write = (): void => {
    const text = nextModule(scan(posix(dir), true).found, resolve(out, '..'))
    if (!existsSync(out) || readFileSync(out, 'utf8') !== text) writeFileSync(out, text)
  }
  write()
  // Dev servers pick up added and removed files. A build reads the folder once.
  if (process.env.NODE_ENV !== 'production' && existsSync(dir)) {
    // Use the long path. On Windows libuv aborts the process watching an 8.3 short one.
    const real = realpathSync.native(dir)
    if (!writers.has(real)) watch(real, () => writers.get(real)?.()).unref()
    writers.set(real, write)
  }
  const webpack = config.webpack
  // Folder shaders load as effects through the GLSL loader. Imports with a query (`?shader` in
  // a glue file) and the site's own `*.frag` rule for Turbopack are left alone.
  const { loader, runtime } = glsl()
  const use = { loader, options: { mode: 'effect' } }
  return {
    ...config,
    webpack: (webpackConfig: WebpackConfig, context: unknown) => {
      const merged = webpack ? webpack(webpackConfig, context) : webpackConfig
      merged.resolve ??= {}
      merged.resolve.alias = {
        ...merged.resolve.alias,
        'diorama/generated$': out,
        '@dioramajs/glsl$': runtime,
      }
      merged.module ??= {}
      merged.module.rules = [
        ...(merged.module.rules ?? []),
        { test: /\.frag$/, include: dir, resourceQuery: { not: [/./] }, use: [use] },
      ]
      return merged
    },
    turbopack: {
      ...config.turbopack,
      resolveAlias: {
        ...config.turbopack?.resolveAlias,
        'dioramajs/generated': `./${posix(relative(root, out))}`,
        '@dioramajs/glsl': runtime,
      },
      rules: { '*.frag': { loaders: [use], as: '*.js' }, ...config.turbopack?.rules },
    },
  }
}

export default withDiorama
